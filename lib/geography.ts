export function countryCodeFor(value: string | undefined): CountryCode | undefined {
  const normalized = value?.trim();

  if (!normalized) {
    return undefined;
  }

  const uppercase = normalized.toUpperCase();
  const byCode = countries.find((country) => country.code === uppercase);

  if (byCode) {
    return byCode.code;
  }

  const byName = countries.find(
    (country) => country.name.toLocaleLowerCase() === normalized.toLocaleLowerCase(),
  );

  return byName?.code;
}

export function countryNameFor(value: string | undefined): string {
  const normalized = value?.trim();

  if (!normalized) {
    return "";
  }

  const code = countryCodeFor(normalized);
  return countries.find((country) => country.code === code)?.name ?? normalized;
}

export function administrativeAreaLabel(country: string | undefined): string {
  switch (countryCodeFor(country)) {
    case "US":
      return "State";
    case "CA":
      return "Province or territory";
    case "AU":
      return "State or territory";
    default:
      return "State, province, or region";
  }
}

export function formatGlobalLocation(location: {
  readonly city?: string;
  readonly administrativeArea?: string;
  readonly country?: string;
}): string {
  const parts = [
    location.city?.trim(),
    location.administrativeArea?.trim(),
    countryNameFor(location.country),
  ].filter((part): part is string => Boolean(part));
  const seen = new Set<string>();

  return parts
    .filter((part) => {
      const key = part.toLocaleLowerCase();

      if (seen.has(key)) {
        return false;
      }

      seen.add(key);
      return true;
    })
    .join(", ");
}
